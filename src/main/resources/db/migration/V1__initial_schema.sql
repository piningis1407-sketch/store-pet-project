-- 1. Users

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(30) NOT NULL,
    email VARCHAR(30) NOT NULL,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(10) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email)
);

-- 2. Categories

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(1000),
    active BOOLEAN NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    type VARCHAR(20) NOT NULL,
    CONSTRAINT uk_categories_name UNIQUE (name)
);

-- 3. Products

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    description VARCHAR(2000),
    price NUMERIC(12, 2) NOT NULL,
    stock_quantity INTEGER NOT NULL,
    image_url VARCHAR(1000),
    active BOOLEAN NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    category_id BIGINT,
    CONSTRAINT fk_products_category
        FOREIGN KEY (category_id) REFERENCES categories(id)
);

-- 4. Carts

CREATE TABLE carts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL,
    user_id BIGINT NOT NULL,
    CONSTRAINT uk_carts_user UNIQUE (user_id),
    CONSTRAINT fk_carts_user
        FOREIGN KEY (user_id) REFERENCES users(id)
);

-- 5. Cart items

CREATE TABLE cart_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quantity INTEGER NOT NULL,
    cart_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    CONSTRAINT uk_cart_product UNIQUE (cart_id, product_id),
    CONSTRAINT fk_cart_items_cart
        FOREIGN KEY (cart_id) REFERENCES carts(id),
    CONSTRAINT fk_cart_items_product
        FOREIGN KEY (product_id) REFERENCES products(id)
);

-- 6. Orders

CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL,
    delivery_address VARCHAR(500) NOT NULL,
    phone VARCHAR(30) NOT NULL,
    recipient_name VARCHAR(30) NOT NULL,
    status VARCHAR(20) NOT NULL,
    total_price NUMERIC(12, 2) NOT NULL,
    user_id BIGINT NOT NULL,
    CONSTRAINT fk_orders_user
        FOREIGN KEY (user_id) REFERENCES users(id)
);

-- 7. Order items

CREATE TABLE order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    price NUMERIC(12, 2) NOT NULL,
    product_name VARCHAR(150) NOT NULL,
    quantity INTEGER NOT NULL,
    subtotal NUMERIC(12, 2) NOT NULL,
    order_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    CONSTRAINT fk_order_items_order
        FOREIGN KEY (order_id) REFERENCES orders(id),
    CONSTRAINT fk_order_items_product
        FOREIGN KEY (product_id) REFERENCES products(id)
);

-- 8. Refresh tokens

CREATE TABLE refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    token_id VARCHAR(36) NOT NULL
);

CREATE UNIQUE INDEX idx_refresh_token_jti
    ON refresh_tokens (token_id);

-- 9. Custom designs

CREATE TABLE custom_designs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_comment VARCHAR(2000),
    background VARCHAR(30) NOT NULL,
    comment VARCHAR(2000),
    created_at TIMESTAMPTZ NOT NULL,
    diameter_cm INTEGER,
    epoxy_color VARCHAR(20),
    epoxy_enabled BOOLEAN NOT NULL,
    estimated_price NUMERIC(12, 2) NOT NULL,
    final_price NUMERIC(12, 2),
    guest_token_hash VARCHAR(64),
    height_cm INTEGER,
    image_url VARCHAR(1000),
    length_cm INTEGER,
    shape VARCHAR(20) NOT NULL,
    status VARCHAR(30) NOT NULL,
    width_cm INTEGER,
    wood_type VARCHAR(20) NOT NULL,
    category_id BIGINT NOT NULL,
    user_id BIGINT,
    CONSTRAINT uk_custom_designs_guest_token UNIQUE (guest_token_hash),
    CONSTRAINT fk_custom_designs_category
        FOREIGN KEY (category_id) REFERENCES categories(id),
    CONSTRAINT fk_custom_designs_user
        FOREIGN KEY (user_id) REFERENCES users(id)
);